const makeSeedBooking = (
    id: string,
    studioId: string,
    dayOffset: number,
    startTime: string,
    endTime: string,
    status: Booking["status"],
): Booking => {
    const studio = seedStudios.find((item) => item.id === studioId)!;
    const hours = calculateHours(startTime, endTime);
    const subtotal = hours * studio.rate;
    const serviceFee = Math.round(subtotal * 0.08);
    return {
        id,
        studioId,
        userEmail: "demo@studionest.co",
        userName: "Maya Chen",
        date: toDateInput(addDays(new Date(), dayOffset)),
        startTime,
        endTime,
        hours,
        guests: 4,
        subtotal,
        serviceFee,
        deposit: studio.deposit,
        total: subtotal + serviceFee + studio.deposit,
        status,
        notes: "Editorial portrait session. We will bring our own styling rack.",
        createdAt: new Date().toISOString(),
    };
};

